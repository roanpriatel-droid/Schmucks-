#!/usr/bin/env node
/**
 * Regenerates the PAIRS map in app/data/pairs.ts from the live catalogue:
 * the his/hers pairs in data/catalogue.json (by design number) resolved to
 * the products' current Shopify handles. Pairs with a missing side are left
 * out, so the file never points at a product that doesn't exist.
 *
 *   node scripts/store-setup/pairs.mjs
 */
import {readFileSync, writeFileSync} from 'node:fs';
import {join} from 'node:path';
import {HERE, paginate, log} from './lib.mjs';

const PRODUCTS = `#graphql
  query PairsProducts($after: String) {
    products(first: 250, after: $after) {
      pageInfo { hasNextPage endCursor }
      nodes { handle title status }
    }
  }`;

const catalogue = JSON.parse(readFileSync(join(HERE, 'data', 'catalogue.json'), 'utf8'));
const products = await paginate(PRODUCTS, (d) => d.products);
const byNumber = new Map();
for (const p of products) {
  const n = p.title.match(/N°\.\s*0*(\d+)/)?.[1];
  if (n && p.status === 'ACTIVE') byNumber.set(n, p.handle);
}

const map = {};
let missing = 0;
for (const [a, b] of catalogue.pairs) {
  const ha = byNumber.get(String(a));
  const hb = byNumber.get(String(b));
  if (!ha || !hb) {
    missing++;
    continue;
  }
  map[ha] = [hb];
  map[hb] = [ha];
}

const file = join(HERE, '..', '..', 'app', 'data', 'pairs.ts');
const src = readFileSync(file, 'utf8');
const body = Object.entries(map)
  .sort(([x], [y]) => x.localeCompare(y))
  .map(([k, v]) => `  '${k}': [${v.map((h) => `'${h}'`).join(', ')}],`)
  .join('\n');
const next = src.replace(
  /export const PAIRS: PairMap = \{[\s\S]*?\n\};/,
  `export const PAIRS: PairMap = {\n  // Generated by scripts/store-setup/pairs.mjs from data/catalogue.json.\n${body}\n};`,
);
writeFileSync(file, next);
log(`Wrote ${Object.keys(map).length} entries (${catalogue.pairs.length - missing} pairs; ${missing} skipped, product not in Shopify yet).`);
